def block(title, pain, rows, less, human, opened=False):
    return ('<details class="more"%s><summary>%s</summary><div class="body"><p>%s</p><div class="ltab uc">%s</div>'
            '<p class="sub" style="margin-top:10px"><b>줄어드는 손일</b> · %s<br><b>끝까지 사람이 하는 일</b> · %s</p></div></details>'
            % (' open' if opened else '', title, pain, ''.join(row(*r) for r in rows), less, human))

